import { Test, TestingModule } from '@nestjs/testing';
import { AutoLetterGenerator } from './auto-letter.generator';
import { LetterService } from './letter.service';
import { LetterTemplateService } from './letter-template.service';
import { PrismaService } from '../../../prisma/prisma.service';
import {
  sha256,
  computeLetterQrHash,
  computeLetterHashChain,
  computeAuditEntryHash,
  computeAuthenticityScore,
  generateLetterQrPayload,
  verifyLetterHashChain,
  verifyAuditChain,
} from '../utils/hash-chain.util';

describe('AutoLetterGenerator', () => {
  let generator: AutoLetterGenerator;
  let letterService: any;
  let templateService: any;
  let prisma: any;

  const mockLetterService = {
    createAutoGenerated: jest.fn().mockResolvedValue({ id: 'letter-auto-1' }),
  };

  const mockTemplateService = {
    findByCode: jest.fn().mockResolvedValue({ id: 'tpl-1', code: 'PERMIT_REQUEST', variables: [] }),
    resolveVariables: jest.fn().mockReturnValue({ subject: 'resolved subject', body: 'resolved body' }),
  };

  const mockPrisma = {
    company: { findUnique: jest.fn().mockResolvedValue({ id: 'c1', nameFa: 'شرکت تست', zone: { nameFa: 'شهرک تست' } }) },
  };

  beforeEach(async () => {
    jest.clearAllMocks();

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        AutoLetterGenerator,
        { provide: LetterService, useValue: mockLetterService },
        { provide: LetterTemplateService, useValue: mockTemplateService },
        { provide: PrismaService, useValue: mockPrisma },
      ],
    }).compile();

    generator = module.get<AutoLetterGenerator>(AutoLetterGenerator);
    letterService = module.get<LetterService>(LetterService);
    templateService = module.get<LetterTemplateService>(LetterTemplateService);
    prisma = module.get<PrismaService>(PrismaService);
  });

  it('should create letter from permit.issued event', async () => {
    await generator.fromPermitIssued({
      id: 'permit-1',
      zoneId: 'zone-1',
      companyId: 'c1',
      type: 'CONSTRUCTION',
      permitNumber: 'PRM-KVH-CON-1403-00001',
      validFrom: new Date(),
      validUntil: new Date(),
      company: { nameFa: 'شرکت تست' },
    });

    expect(letterService.createAutoGenerated).toHaveBeenCalled();
  });

  it('should use correct template for each event type', async () => {
    await generator.fromWaybillApproved({
      id: 'w1', zoneId: 'z1', companyId: 'c1',
      waybillNumber: 'WB-001', cargoDescription: 'test',
      cargoCategory: 'RAW_MATERIAL', netWeight: 10, vehiclePlate: '۱۲ع۳۴',
    });

    expect(templateService.findByCode).toHaveBeenCalledWith('WAYBILL_APPROVED', 'z1');
  });

  it('should set isAutoGenerated=true + sourceModule', async () => {
    await generator.fromPermitSubmitted({
      id: 'p1', zoneId: 'z1', companyId: 'c1',
      type: 'HOT_WORK', requestNumber: 'PR-001',
      requestedFrom: new Date(), requestedUntil: new Date(),
      company: { nameFa: 'co' },
    });

    expect(letterService.createAutoGenerated).toHaveBeenCalledWith(
      expect.objectContaining({ sourceModule: 'PERMIT' }),
      'z1',
    );
  });

  it('should not throw if template not found - log warning only', async () => {
    templateService.findByCode.mockResolvedValueOnce(null);

    const result = await generator.fromPermitIssued({ id: 'p1', zoneId: 'z1', companyId: 'c1', type: 'CON', permitNumber: 'N', validFrom: new Date(), validUntil: new Date() });
    expect(result).toBeNull();
  });
});

describe('HashChain', () => {
  it('should compute deterministic qrHash', () => {
    const hash1 = computeLetterQrHash('KVH/1403/000001', 'zone-1', 'subject', '2024-01-01T00:00:00.000Z');
    const hash2 = computeLetterQrHash('KVH/1403/000001', 'zone-1', 'subject', '2024-01-01T00:00:00.000Z');
    expect(hash1).toBe(hash2);
    expect(hash1).toHaveLength(64);
  });

  it('should chain each letter to the previous', () => {
    const chain1 = computeLetterHashChain(null, 'R1', 'body1');
    const chain2 = computeLetterHashChain(chain1, 'R2', 'body2');
    expect(chain1).not.toBe(chain2);
    // SHA-256 is one-way: chain2 depends on chain1 but doesn't contain it as substring
    expect(chain2).toHaveLength(64);
    // Verify chain2 is different when chain1 changes
    const chain2Alt = computeLetterHashChain('different', 'R2', 'body2');
    expect(chain2).not.toBe(chain2Alt);
  });

  it('should detect tampering in chain verification', () => {
    const chain1 = computeLetterHashChain(null, 'R1', 'original');
    const tampered = computeLetterHashChain(null, 'R1', 'tampered');
    expect(chain1).not.toBe(tampered);

    const valid = verifyLetterHashChain([
      { hashChain: chain1, previousHash: null, registryNumber: 'R1', body: 'original' },
    ]);
    expect(valid).toBe(true);

    const invalid = verifyLetterHashChain([
      { hashChain: tampered, previousHash: null, registryNumber: 'R1', body: 'original' },
    ]);
    expect(invalid).toBe(false);
  });

  it('should produce valid genesis hash for first letter', () => {
    const hash = computeLetterHashChain(null, 'R1', 'body');
    expect(hash).toHaveLength(64);
    expect(hash).toBe(sha256(`GENESISR1body`));
  });

  it('should verify audit entries chain correctly', () => {
    const ts1 = '2024-01-01T00:00:00.000Z';
    const ts2 = '2024-01-01T01:00:00.000Z';
    const h1 = computeAuditEntryHash(null, 'CREATED', 'u1', ts1);
    const h2 = computeAuditEntryHash(h1, 'SUBMITTED', 'u1', ts2);

    const valid = verifyAuditChain([
      { hash: h1, previousHash: null, action: 'CREATED', actorId: 'u1', timestamp: new Date(ts1) },
      { hash: h2, previousHash: h1, action: 'SUBMITTED', actorId: 'u1', timestamp: new Date(ts2) },
    ]);
    expect(valid).toBe(true);
  });

  it('should compute authenticityScore correctly', () => {
    expect(computeAuthenticityScore({ approvalComplete: true, hasDispatchRecord: true, hashChainValid: true, slaNotBreached: true })).toBe(100);
    expect(computeAuthenticityScore({ approvalComplete: false, hasDispatchRecord: false, hashChainValid: false, slaNotBreached: false })).toBe(0);
    expect(computeAuthenticityScore({ approvalComplete: true, hasDispatchRecord: false, hashChainValid: true, slaNotBreached: false })).toBe(50);
  });

  it('should generate correct QR payload', () => {
    const payload = generateLetterQrPayload('KVH/1403/000001', 'abc123');
    expect(payload).toBe('IDOP:LETTER:KVH/1403/000001:abc123');
  });
});

describe('RegistryCounter', () => {
  it('should generate sequential numbers', () => {
    const seq1 = computeLetterHashChain(null, 'R1', 'b1');
    const seq2 = computeLetterHashChain(null, 'R2', 'b2');
    expect(seq1).not.toBe(seq2);
  });

  it('should format as {zoneCode}/{year}/{seq:06d}', () => {
    // This is tested in LetterService.create
    const registryNumber = `KVH/1403/${String(1).padStart(6, '0')}`;
    expect(registryNumber).toBe('KVH/1403/000001');
  });
});
