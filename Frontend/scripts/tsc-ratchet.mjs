#!/usr/bin/env node
/**
 * tsc ratchet (fix4.md, Revised Task 2 item 2).
 *
 * The frontend carries a large PRE-EXISTING type backlog that is out of scope to
 * zero out. This script makes that backlog explicit and non-growing: it compares
 * a fresh `tsc --noEmit` run against a committed baseline and fails if ANY error
 * is not already recorded there.
 *
 *   node scripts/tsc-ratchet.mjs            # check (exit 1 on any NEW error)
 *   node scripts/tsc-ratchet.mjs --update   # regenerate the baseline
 *
 * Matching is by file + line + code, per spec. Note the consequence: fixing an
 * error can shift line numbers within that file and make untouched errors look
 * "new". Regenerate the baseline with --update after any deliberate fix pass
 * (that is exactly what the spec's step 5 prescribes).
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = dirname(frontendRoot);
const baselinePath = join(repoRoot, 'docs', 'tsc-baseline.txt');
const update = process.argv.includes('--update') || process.argv.includes('--write');

// ---- run tsc -------------------------------------------------------------
const tscBin = join(frontendRoot, 'node_modules', 'typescript', 'bin', 'tsc');
const result = existsSync(tscBin)
  ? spawnSync(process.execPath, [tscBin, '--noEmit', '-p', 'tsconfig.json'], {
      cwd: frontendRoot,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    })
  : spawnSync('npx', ['tsc', '--noEmit', '-p', 'tsconfig.json'], {
      cwd: frontendRoot,
      shell: true,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });

if (result.error) {
  console.error(`FAIL: could not run tsc: ${result.error.message}`);
  process.exit(1);
}

const output = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;

// ---- parse ---------------------------------------------------------------
// tsc emits:  src/App.tsx(3,3): error TS2305: message
const ERROR_RE = /^(.+?)\((\d+),(\d+)\): error (TS\d+):/;
const current = new Map(); // key -> raw line
const byArea = new Map();
const byCode = new Map();

for (const raw of output.split(/\r?\n/)) {
  const line = raw.trim();
  if (!line) continue;
  const m = ERROR_RE.exec(line);
  if (!m) continue;
  const file = m[1].replace(/\\/g, '/');
  const key = `${file}|${m[2]}|${m[4]}`;
  if (!current.has(key)) current.set(key, line);

  const parts = file.split('/');
  const area = parts.length > 2 ? parts.slice(0, 3).join('/') : parts.slice(0, 2).join('/');
  byArea.set(area, (byArea.get(area) ?? 0) + 1);
  byCode.set(m[4], (byCode.get(m[4]) ?? 0) + 1);
}

// ---- update mode ---------------------------------------------------------
if (update) {
  mkdirSync(dirname(baselinePath), { recursive: true });
  const header = [
    '# tsc baseline -- generated by scripts/tsc-ratchet.mjs --update',
    '# Do not edit by hand. Format: <file>|<line>|<TS code>   (one per line)',
    `# total: ${current.size}`,
    '',
  ];
  const keys = [...current.keys()].sort();
  writeFileSync(baselinePath, `${header.join('\n')}${keys.join('\n')}\n`, 'utf8');
  console.log(`Baseline written: ${baselinePath}`);
  console.log(`Total errors recorded: ${current.size}`);
  process.exit(0);
}

// ---- check mode ----------------------------------------------------------
if (!existsSync(baselinePath)) {
  console.error(`FAIL: baseline not found at ${baselinePath}`);
  console.error('Create it first with:  npm run typecheck:ratchet -- --update');
  process.exit(1);
}

const baseline = new Set(
  readFileSync(baselinePath, 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#')),
);

const isNew = [...current.keys()].filter((k) => !baseline.has(k));
const isFixed = [...baseline].filter((k) => !current.has(k));

console.log(`Baseline errors : ${baseline.size}`);
console.log(`Current errors  : ${current.size}`);
console.log(`New (regressions): ${isNew.length}`);
console.log(`Fixed since baseline: ${isFixed.length}`);

if (isNew.length > 0) {
  console.error('\nFAIL: new tsc errors not present in the baseline:');
  for (const k of isNew.slice(0, 60)) console.error(`  x ${current.get(k)}`);
  if (isNew.length > 60) console.error(`  ... and ${isNew.length - 60} more`);
  process.exit(1);
}

if (isFixed.length > 0) {
  console.log('\nErrors fixed since the baseline was captured (run --update to lock this in):');
  const fixedByArea = new Map();
  for (const k of isFixed) {
    const area = k.split('|')[0].split('/').slice(0, 3).join('/');
    fixedByArea.set(area, (fixedByArea.get(area) ?? 0) + 1);
  }
  for (const [area, n] of [...fixedByArea].sort((a, b) => b[1] - a[1]).slice(0, 15)) {
    console.log(`  - ${String(n).padStart(5)}  ${area}`);
  }
}

console.log('\nTop areas (current):');
for (const [area, n] of [...byArea].sort((a, b) => b[1] - a[1]).slice(0, 12)) {
  console.log(`  ${String(n).padStart(5)}  ${area}`);
}

console.log('\nPASS: no tsc errors outside the baseline.');
