import { useState, useMemo } from "react";
import {
  Star, Clock, AlertCircle, CheckCircle2, FileText, Inbox, Send,
  Archive, Pen, QrCode, LayoutTemplate,
} from "lucide-react";
import { LetterV2, LETTERS_V2 } from "@/entities/letter";
import type { Letter } from "@/modules/correspondence/types";
import { PersianTable, Column } from "@/shared/components/ui/PersianTable";
import { SearchPanel, SearchFilters } from "./SearchPanel";

// ── Convert store Letter → display LetterV2 ───────────────────────────────────
function storeLetterToV2(l: Letter): LetterV2 {
  return {
    id: l.id,
    registryNumber: l.registryNumber,
    direction: l.direction as LetterV2["direction"],
    type: l.type as LetterV2["type"],
    classification: l.classification as LetterV2["classification"],
    priority: (l.priority === "instant" || l.priority === "urgent" || l.priority === "normal" || l.priority === "low")
      ? l.priority : "normal",
    subject: l.subject,
    referenceLetterId: l.referenceLetterId,
    sender: l.sender,
    senderOrg: l.senderOrg,
    senderRole: l.senderRole,
    recipients: l.recipients.map(r => ({ name: r.name, org: r.org, role: r.action })),
    cc: [],
    approvalChain: (l.approvalChain ?? []).map(s => ({
      name: s.assigneeName || s.assigneeRole,
      role: s.assigneeRole,
      type: (s.type as any) ?? "reviewer",
      status: (s.status === "approved" || s.status === "rejected" || s.status === "returned")
        ? s.status : "pending",
      date: s.completedAt,
      comment: s.comment,
    })),
    annotations: [],
    status: l.status as LetterV2["status"],
    enclosuresCount: l.attachments?.length ?? 0,
    createdAt: l.createdAt,
    updatedAt: l.updatedAt,
    responseDeadline: l.responseDeadline,
    slaHours: l.slaHours,
    registryYear: l.registryYear ?? 1403,
    qrHash: l.qrHash,
  };
}

const CATEGORY_CFG = [
  { id: "inbox",            label: "دریافتی",          icon: Inbox },
  { id: "pending-approval", label: "در انتظار تأیید",  icon: Clock },
  { id: "draft",            label: "پیش‌نویس",          icon: Pen },
  { id: "sent",             label: "ارسال شده",         icon: Send },
  { id: "archived",         label: "بایگانی",           icon: Archive },
];

const DIRECTION_LABELS: Record<string, string> = {
  incoming: "ورودی", outgoing: "خروجی", internal: "داخلی",
};
const TYPE_LABELS: Record<string, string> = {
  official: "رسمی", memo: "یادداشت", circular: "بخشنامه",
  report: "گزارش", instruction: "دستورالعمل", request: "درخواست", response: "پاسخ",
};
const PRIORITY_MAP: Record<string, { fa: string; text: string; bg: string }> = {
  instant: { fa: "فوری",      text: "text-red-700",   bg: "bg-red-50" },
  urgent:  { fa: "ضروری",     text: "text-amber-700", bg: "bg-amber-50" },
  normal:  { fa: "عادی",      text: "text-slate-600", bg: "bg-slate-100" },
  low:     { fa: "کم‌اهمیت",  text: "text-blue-700",  bg: "bg-blue-50" },
};
const STATUS_LABELS: Record<string, string> = {
  draft: "پیش‌نویس", "pending-approval": "در انتظار تأیید", approved: "تأیید شده",
  sent: "ارسال شده", dispatched: "ارسال شده", archived: "بایگانی شده",
};

function isOverdue(letter: LetterV2): boolean {
  if (!letter.responseDeadline || letter.status === "archived" || letter.status === "sent") return false;
  return new Date(letter.responseDeadline) < new Date();
}

interface LetterListProps {
  onSelect: (letter: LetterV2) => void;
  onCompose: () => void;
  activeCategory: string;
  onCategoryChange: (cat: string) => void;
  onShowRegistry: () => void;
  onShowStats: () => void;
  onShowArchive: () => void;
  storeLetters?: Letter[];
}

export function LetterList({
  onSelect, onCompose, activeCategory, onCategoryChange,
  onShowRegistry, onShowStats, onShowArchive, storeLetters = [],
}: LetterListProps) {
  const [filters, setFilters] = useState<SearchFilters>({
    query: "", direction: "", type: "", classification: "", priority: "", dateFrom: "", dateTo: "",
  });

  // Merge static seed letters with live store letters (store letters appear first)
  const allLetters: LetterV2[] = useMemo(() => {
    const converted = storeLetters.map(storeLetterToV2);
    const seedIds = new Set(converted.map(l => l.id));
    const deduped = LETTERS_V2.filter(l => !seedIds.has(l.id));
    return [...converted, ...deduped];
  }, [storeLetters]);

  // Category counts from merged list
  const categoriesWithCounts = CATEGORY_CFG.map((cat) => ({
    ...cat,
    count: allLetters.filter((l) => {
      if (cat.id === "inbox") return l.direction === "incoming";
      return l.status === cat.id;
    }).length,
  }));

  // Auto-generated count (from store)
  const autoGeneratedCount = storeLetters.filter(l =>
    l.tags?.includes("auto-generated")
  ).length;

  const filtered = useMemo(() => {
    return allLetters.filter((l) => {
      const matchCat =
        activeCategory === "inbox"           ? l.direction === "incoming"
        : activeCategory === "pending-approval" ? l.status === "pending-approval"
        : l.status === activeCategory;
      const matchQuery = !filters.query ||
        l.subject.includes(filters.query) ||
        l.sender.includes(filters.query) ||
        l.registryNumber.includes(filters.query);
      const matchDir   = !filters.direction || l.direction === filters.direction;
      const matchType  = !filters.type || l.type === filters.type;
      const matchClass = !filters.classification || l.classification === filters.classification;
      const matchPri   = !filters.priority || l.priority === filters.priority;
      return matchCat && matchQuery && matchDir && matchType && matchClass && matchPri;
    });
  }, [activeCategory, filters, allLetters]);

  const columns: Column<LetterV2>[] = [
    {
      key: "star", header: "", width: "36px",
      render: (l) => (
        <Star className={`w-3.5 h-3.5 ${
          (l as any).starred ? "text-amber-500 fill-amber-500" : "text-muted-foreground/30"
        }`} />
      ),
    },
    {
      key: "registryNumber", header: "شماره", sortable: true, width: "140px",
      render: (l) => (
        <div>
          <span className="font-mono text-xs text-foreground">{l.registryNumber}</span>
          {(l as any).qrHash && (
            <span title="دارای QR اعتبارسنجی">
              <QrCode className="w-2.5 h-2.5 text-accent inline mr-1" />
            </span>
          )}
        </div>
      ),
    },
    {
      key: "subject", header: "موضوع", sortable: true,
      render: (l) => (
        <div className="min-w-0">
          <p className="text-xs font-bold text-foreground truncate">{l.subject}</p>
          <p className="text-[10px] text-muted-foreground truncate mt-0.5">{l.sender} · {l.senderOrg}</p>
        </div>
      ),
    },
    {
      key: "direction", header: "جهت", width: "80px",
      render: (l) => (
        <span className={`text-[10px] px-1.5 py-0.5 rounded ${
          l.direction === "incoming" ? "bg-blue-50 text-blue-700"
          : l.direction === "outgoing" ? "bg-emerald-50 text-emerald-700"
          : "bg-secondary text-muted-foreground"
        }`}>
          {DIRECTION_LABELS[l.direction]}
        </span>
      ),
    },
    {
      key: "type", header: "نوع", width: "80px",
      render: (l) => <span className="text-[10px] text-muted-foreground">{TYPE_LABELS[l.type]}</span>,
    },
    {
      key: "priority", header: "اولویت", sortable: true, width: "80px",
      render: (l) => {
        const p = PRIORITY_MAP[l.priority] ?? PRIORITY_MAP.normal;
        return <span className={`text-[10px] px-1.5 py-0.5 rounded ${p.bg} ${p.text}`}>{p.fa}</span>;
      },
    },
    {
      key: "status", header: "وضعیت", width: "110px",
      render: (l) => {
        const overdue = isOverdue(l);
        const isAuto = (l as any).tags?.includes?.("auto-generated");
        return (
          <div className="flex items-center gap-1 flex-wrap">
            {overdue && <AlertCircle className="w-3 h-3 text-red-500 flex-shrink-0" />}
            <span className={`text-[10px] px-1.5 py-0.5 rounded ${
              overdue ? "bg-red-50 text-red-700" : "bg-secondary text-muted-foreground"
            }`}>
              {overdue ? "تأخیر" : STATUS_LABELS[l.status]}
            </span>
            {isAuto && (
              <span className="text-[8px] px-1 py-0.5 rounded bg-accent/10 text-accent font-medium">خودکار</span>
            )}
          </div>
        );
      },
    },
    {
      key: "createdAt", header: "تاریخ", sortable: true, width: "100px",
      render: (l) => <span className="text-[10px] text-muted-foreground font-mono">{l.createdAt}</span>,
    },
  ];

  return (
    <div className="flex h-full" dir="rtl">
      {/* Sidebar */}
      <div className="w-56 flex-shrink-0 bg-card border-l border-border flex flex-col">
        <div className="p-4 border-b border-border">
          <h2 className="text-sm font-bold text-foreground flex items-center gap-2">
            <FileText className="w-4 h-4 text-primary" />
            دبیرخانه
          </h2>
          <p className="text-[10px] text-muted-foreground mt-0.5">سیستم مدیریت مکاتبات</p>
        </div>

        <div className="p-3 flex-1 overflow-y-auto">
          {/* Compose button */}
          <button
            onClick={onCompose}
            className="w-full flex items-center justify-center gap-2 bg-accent text-white text-xs font-bold py-2.5 rounded-lg mb-3"
          >
            <Pen className="w-3.5 h-3.5" />
            نامه جدید
          </button>

          {/* Auto-generated badge */}
          {autoGeneratedCount > 0 && (
            <div className="flex items-center gap-2 px-3 py-2 mb-2 bg-primary/5 border border-primary/20 rounded-lg">
              <LayoutTemplate className="w-3.5 h-3.5 text-primary flex-shrink-0" />
              <div className="flex-1 min-w-0">
                <p className="text-[10px] text-primary font-medium">نامه خودکار</p>
                <p className="text-[9px] text-muted-foreground">{autoGeneratedCount} نامه تولید شده</p>
              </div>
            </div>
          )}

          {/* Category nav */}
          {categoriesWithCounts.map((cat) => (
            <button
              key={cat.id}
              onClick={() => onCategoryChange(cat.id)}
              className={`w-full flex items-center gap-2.5 border-r-2 px-3 py-2 rounded-lg text-xs mb-1 transition-colors ${
                activeCategory === cat.id
                  ? "border-primary bg-secondary text-secondary-foreground font-bold"
                  : "border-transparent font-medium text-foreground/75 hover:bg-secondary hover:text-foreground"
              }`}
            >
              <cat.icon className="w-4 h-4" />
              <span className="flex-1 text-right">{cat.label}</span>
              {cat.count > 0 && (
                <span className="text-[10px] bg-secondary rounded-full px-1.5 py-0.5">{cat.count}</span>
              )}
            </button>
          ))}

          {/* Secondary nav */}
          <div className="mt-4 pt-3 border-t border-border space-y-1">
            <button
              onClick={onShowRegistry}
              className="w-full flex items-center gap-2.5 border-r-2 border-transparent px-3 py-2 rounded-lg text-xs font-medium text-foreground/75 hover:bg-secondary hover:text-foreground"
            >
              <FileText className="w-4 h-4" />
              <span>دفتر ثبت</span>
            </button>
            <button
              onClick={onShowArchive}
              className="w-full flex items-center gap-2.5 border-r-2 border-transparent px-3 py-2 rounded-lg text-xs font-medium text-foreground/75 hover:bg-secondary hover:text-foreground"
            >
              <Archive className="w-4 h-4" />
              <span>آرشیو فیزیکی</span>
            </button>
            <button
              onClick={onShowStats}
              className="w-full flex items-center gap-2.5 border-r-2 border-transparent px-3 py-2 rounded-lg text-xs font-medium text-foreground/75 hover:bg-secondary hover:text-foreground"
            >
              <CheckCircle2 className="w-4 h-4" />
              <span>آمار و گزارش</span>
            </button>
            {/* QR verify shortcut */}
            <a
              href="/verify?mode=letter"
              target="_blank"
              rel="noreferrer"
              className="w-full flex items-center gap-2.5 border-r-2 border-transparent px-3 py-2 rounded-lg text-xs font-medium text-foreground/75 hover:bg-secondary hover:text-foreground"
            >
              <QrCode className="w-4 h-4" />
              <span>اعتبارسنجی QR</span>
            </a>
          </div>
        </div>

        {/* Footer stats */}
        <div className="p-3 border-t border-border">
          <div className="bg-secondary rounded-lg p-3">
            <p className="text-[10px] text-muted-foreground">آمار ماهانه</p>
            <div className="flex items-center gap-2 mt-1">
              <span className="text-lg font-bold text-foreground">{allLetters.length}</span>
              <span className="text-[10px] text-muted-foreground">نامه ثبت‌شده</span>
            </div>
            {autoGeneratedCount > 0 && (
              <p className="text-[9px] text-accent mt-0.5">{autoGeneratedCount} نامه خودکار</p>
            )}
          </div>
        </div>
      </div>

      {/* Main list */}
      <div className="flex-1 flex flex-col overflow-hidden bg-background">
        <SearchPanel filters={filters} onChange={setFilters} />
        <div className="flex items-center justify-between px-4 py-2 border-b border-border">
          <span className="text-[10px] text-muted-foreground">{filtered.length} نامه</span>
          {storeLetters.length > 0 && (
            <span className="text-[10px] text-accent flex items-center gap-1">
              <LayoutTemplate className="w-3 h-3" />
              {storeLetters.length} نامه خودکار در سیستم
            </span>
          )}
        </div>
        <div className="flex-1 overflow-auto">
          <PersianTable
            columns={columns}
            data={filtered}
            pageSize={15}
            keyExtractor={(l) => l.id}
            onRowClick={onSelect}
            emptyMessage="نامه‌ای یافت نشد"
          />
        </div>
      </div>
    </div>
  );
}
